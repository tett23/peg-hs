#!/usr/bin/env python3
"""Generate the HTML entity table used by the CommonMark conformance test
from the vendored WHATWG entities.json. Only names ending in ';' are kept,
since CommonMark requires the semicolon."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent / "conformance"
data = json.loads((root / "data/whatwg-entities/entities.json").read_text())
rows = sorted(
    (name[1:-1], "".join(chr(c) for c in v["codepoints"]))
    for name, v in data.items()
    if name.endswith(";")
)

def hs(s):
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else "\\" + str(ord(c)) + "\\&" for c in s) + '"'

out = [
    "-- | HTML named character references, generated by scripts/gen-entities.py",
    "-- from data/whatwg-entities/entities.json (WHATWG, CC BY 4.0). Do not edit.",
    "module Conformance.CommonMark.Entities",
    "  ( entities",
    "  ) where",
    "",
    "import Data.Map.Strict (Map)",
    "import qualified Data.Map.Strict as M",
    "import Data.Text (Text)",
    "import qualified Data.Text as T",
    "",
    "-- | Entity names without the leading @&@ and trailing @;@.",
    "entities :: Map Text Text",
    "entities =",
    "  M.fromDistinctAscList",
    "    [ " + "\n    , ".join("(T.pack %s, T.pack %s)" % (hs(n), hs(v)) for n, v in rows),
    "    ]",
    "",
]
(root / "commonmark/Conformance/CommonMark/Entities.hs").write_text("\n".join(out))
print(len(rows), "entities")
