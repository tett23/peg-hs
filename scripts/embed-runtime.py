#!/usr/bin/env python3
"""Write packages/peg-cli/app/Embedded.hs: the sources that peg-hs parse
compiles with a generated parser (ADR 0036). They are the sources of
peg-runtime and the pretty-printer of peg-cli; a test of peg-cli checks
that the module is up to date."""
import os

root = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))
runtime = os.path.join(root, 'packages/peg-runtime/src')


def literal(text):
    out = ['"']
    for i, c in enumerate(text):
        nxt = text[i + 1] if i + 1 < len(text) else ''
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif c == '\n':
            out.append('\\n')
        elif ' ' <= c <= '~':
            out.append(c)
        else:
            out.append('\\%d' % ord(c))
            if nxt.isdigit():
                out.append('\\&')
    out.append('"')
    return ''.join(out)


files = []
for d, _, names in os.walk(runtime):
    for n in names:
        if n.endswith('.hs'):
            p = os.path.join(d, n)
            files.append((os.path.relpath(p, runtime), open(p, encoding='utf-8').read()))
files.sort()
pretty = open(os.path.join(root, 'packages/peg-cli/app/Pretty.hs'), encoding='utf-8').read()

lines = [
    '-- This module was generated by scripts/embed-runtime.py. Do not edit it by hand.',
    '',
    '-- | The sources that peg-hs parse compiles with a generated parser',
    '-- (ADR 0036): those of peg-runtime, and the pretty-printer.',
    'module Embedded (runtimeSources, prettySource) where',
    '',
    '-- | The modules of peg-runtime, by their paths under @src@.',
    'runtimeSources :: [(FilePath, String)]',
    'runtimeSources =',
]
for i, (path, text) in enumerate(files):
    lines.append('  %s (%s, %s)' % ('[' if i == 0 else ',', literal(path), literal(text)))
lines.append('  ]')
lines += ['', '-- | @app/Pretty.hs@.', 'prettySource :: String', 'prettySource = ' + literal(pretty)]
with open(os.path.join(root, 'packages/peg-cli/app/Embedded.hs'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
