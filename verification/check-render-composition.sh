#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
scratch=${1:?pass the shared temporary verification directory}
: "${LEAN_PATH:?set LEAN_PATH to the shared Lean object directory}"

(cd verification && lean -DwarningAsError=true \
  -o "$scratch/RenderComposition.olean" RenderComposition.lean) \
  > "$scratch/RenderComposition.log"
if grep -Fq 'sorryAx' "$scratch/RenderComposition.log"; then
  cat "$scratch/RenderComposition.log" >&2
  exit 1
fi

cat > "$scratch/RenderCompositionSource.expected" <<'SOURCE'
render opts g an marker =
  T.intercalate
    "\n"
    ( [ "-- This module was generated by peg-hs from " <> T.pack (optSourceName opts) <> ". Do not edit it by hand."
      , "-- It needs " <> runtimeVersions <> "."
      ]
        ++ ["{-# LANGUAGE " <> unLoc x <> " #-}" | x <- grammarLanguages g]
        ++ ["{-# OPTIONS_GHC -Wno-unused-imports -Wno-unused-top-binds #-}" | pruned]
        ++ [ "module " <> unLoc (grammarModule g)
      , "  ( " <> T.intercalate "\n  , " exports
      , "  ) where"
      , ""
      ]
        ++ ["import qualified Prelude as PegPrelude" | usesPegPrelude]
        ++ [ "import qualified Peg.Runtime.Internal as PegRt"
           ]
        ++ ["import Prelude" | not (importsPrelude g)]
        ++ [""]
        ++ map verbatimBlock (grammarVerbatim g)
        ++ decls
SOURCE
sed -n '/^render opts g an marker =$/,/^        ++ decls$/p' \
  packages/peg-codegen/src/Peg/Codegen.hs > "$scratch/RenderCompositionSource.actual"
diff -u "$scratch/RenderCompositionSource.expected" "$scratch/RenderCompositionSource.actual"

cat > "$scratch/RenderCompositionDecls.expected" <<'SOURCE'
    decls =
      dataDecls
        ++ entryDecls
        ++ syntaxEntryDecls
        ++ recoverEntryDecls
        ++ debugDecls
        ++ syntaxDecls env keep
        ++ (if keep "peg'config" then [configDecl] else [])
        ++ (if keep "peg'newStore" then [storeDecl, newStoreDecl] else [])
        ++ [ruleDecl env r | r <- grammarRules g, keep (ruleVar (ruleName r))]
SOURCE
sed -n '/^    decls =$/,/^        ++ \[ruleDecl env r |/p' \
  packages/peg-codegen/src/Peg/Codegen.hs > "$scratch/RenderCompositionDecls.actual"
diff -u "$scratch/RenderCompositionDecls.expected" "$scratch/RenderCompositionDecls.actual"

sed 's/\[\.terminal 19\] ++ name ++ exportWord exports/[.terminal 20] ++ name ++ exportWord exports/' \
  verification/RenderComposition.lean > "$scratch/RenderCompositionInvalid.lean"
if cmp -s verification/RenderComposition.lean "$scratch/RenderCompositionInvalid.lean"; then
  echo 'Render composition mutation did not change the module token' >&2
  exit 1
fi
if (cd verification && lean -DwarningAsError=true \
    "$scratch/RenderCompositionInvalid.lean") \
    > "$scratch/RenderCompositionInvalid.log" 2>&1; then
  echo 'Lean accepted a changed module token' >&2
  exit 1
fi
grep -Fq 'error: Type mismatch' "$scratch/RenderCompositionInvalid.log" || {
  cat "$scratch/RenderCompositionInvalid.log" >&2
  exit 1
}

printf 'Render composition: 18 Lean theorems, 2 exact source checks, 1 rejected mutation, 0 sorry axioms.\n'
