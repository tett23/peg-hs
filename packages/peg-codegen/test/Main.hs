genExpr :: Gen Text
genExpr = T.pack <$> sized go
  where
    go n
      | n <= 1 = atom
      | otherwise =
          oneof
            [ atom
            , do a <- go (n `div` 2); o <- elements ["+", "-", "*"]; s1 <- sp; s2 <- sp; b <- go (n `div` 2); pure (a <> s1 <> o <> s2 <> b)
            , do s1 <- sp; s2 <- sp; a <- go (n `div` 2); pure ("(" <> s1 <> a <> s2 <> ")")
            ]
    atom = show <$> (choose (0, 999) :: Gen Int)
    sp = elements ["", " ", "  ", "\n", " # c\n", "\t"]

