-- Generate a fixture with only the given names exported, optionally from
-- the grammar without its labels.
generateExports :: String -> Maybe Text -> Bool -> [Text] -> IO (Either [Diagnostic] Text)
generateExports n strip debug names = do
  src <- TIO.readFile (fixtureSource n)
  let opts = (fixtureOptions n) {optDebugEntry = debug, optExports = Just names}
  pure $ case strip of
    Nothing -> generateFromSource opts src
    Just m -> parseGrammar src >>= generate opts . stripLabelsAs m

generatedExports :: String -> Maybe Text -> Bool -> [Text] -> IO Text
generatedExports n strip debug names =
  generateExports n strip debug names >>= \case
    Left ds -> assertFailure (show ds) >> pure ""
    Right code -> pure code

-- The export list of a module: from the module line to @) where@.
exportList :: Text -> Text
exportList code = T.unlines (upTo (dropWhile (not . T.isPrefixOf "module ") (T.lines code)))
  where
    upTo ls = case break (== "  ) where") ls of
      (before, end : _) -> before ++ [end]
      (before, []) -> before

