    Left ds -> assertFailure (show ds) >> pure (ExitFailure 1, "")
    Right code -> do
      TIO.writeFile (dir </> name <> ".hs") code
      (ex, _, err) <-
        readProcessWithExitCode
          ghc
          (flags ++ ["-fno-code", "-i../peg-runtime/src", "-outputdir", dir </> "out", dir </> name <> ".hs"])
          ""
      pure (ex, err)

